#!/usr/bin/env node
// Генерирует src/data/bios/libretroSystemDat.ts из libretro System.dat.
// Generates src/data/bios/libretroSystemDat.ts from the libretro System.dat.
//
// Источник / source: https://github.com/libretro/libretro-database/blob/master/dat/System.dat
// Лицензия данных / data license: CC BY-SA 4.0 (libretro-database).
//
// Использование / usage:
//   node scripts/gen-bios-db.mjs path/to/System.dat
//   node scripts/gen-bios-db.mjs            # скачает свежий файл / downloads the latest file
import fs from 'node:fs';
import path from 'node:path';

const SRC_URL = 'https://raw.githubusercontent.com/libretro/libretro-database/master/dat/System.dat';
const OUT = path.resolve('src/data/bios/libretroSystemDat.ts');

async function readSource() {
  const arg = process.argv[2];
  if (arg) return fs.readFileSync(arg, 'utf8');
  const resp = await fetch(SRC_URL);
  if (!resp.ok) throw new Error(`HTTP ${resp.status} for ${SRC_URL}`);
  return resp.text();
}

function parse(text) {
  const version = (text.match(/^\s*version\s+(\S+)/m) || [])[1] || 'unknown';
  const systems = [];
  const entries = [];
  let current = -1;
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    const c = line.match(/^comment\s+"(.+)"$/);
    if (c) {
      const name = c[1];
      if (name === 'System' || name.startsWith('System, firmware')) continue;
      systems.push(name);
      current = systems.length - 1;
      continue;
    }
    if (!line.startsWith('rom (')) continue;
    const name = (line.match(/name\s+"([^"]+)"/) || line.match(/name\s+(\S+)/) || [])[1];
    const size = Number((line.match(/size\s+(\d+)/) || [])[1] || 0);
    const crc = ((line.match(/crc\s+([0-9A-Fa-f]{8})/) || [])[1] || '').toLowerCase();
    const md5 = ((line.match(/md5\s+([0-9A-Fa-f]{32})/) || [])[1] || '').toLowerCase();
    if (!name || !md5 || current < 0) continue;
    entries.push([current, name, size, crc, md5]);
  }
  return { version, systems, entries };
}

const { version, systems, entries } = parse(await readSource());
const lines = [
  '// AUTO-GENERATED by scripts/gen-bios-db.mjs — не редактировать вручную / do not edit by hand.',
  '// Источник / source: libretro-database dat/System.dat ' + version,
  '// https://github.com/libretro/libretro-database — CC BY-SA 4.0',
  '',
  `export const LIBRETRO_SYSTEM_DAT_VERSION = '${version}';`,
  '',
  'export const LIBRETRO_BIOS_SYSTEMS: string[] = ' + JSON.stringify(systems, null, 2) + ';',
  '',
  '/** [systemIndex, relativePath, size, crc32, md5] */',
  'export type LibretroBiosRow = [number, string, number, string, string];',
  '',
  'export const LIBRETRO_BIOS_ROWS: LibretroBiosRow[] = [',
  ...entries.map((e) => '  ' + JSON.stringify(e) + ','),
  '];',
  '',
];
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join('\n'));
console.log(`OK: ${entries.length} files, ${systems.length} systems, ${version} -> ${path.relative(process.cwd(), OUT)}`);
